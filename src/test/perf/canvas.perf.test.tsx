import { act, render } from '@testing-library/react';
import { Bounds, Position, Size } from '../../domain/shared';
import {
  createCanvasViewportStore,
  createSelectionStore,
  elementContentBounds,
  findSelectableAt,
  findSelectablesInBounds,
  toSelectableItems,
} from '../../application/services';
import { Canvas } from '../../presentation/canvas/components/canvas';
import { describeBoard, describeElement } from '../../presentation/canvas/accessibility';
import { generateElements } from '../fixtures/generate-elements';
import {
  formatMetric,
  formatMetricsTable,
  heapUsedBytes,
  measure,
  measureSamples,
  requestGarbageCollection,
  summarize,
} from './measure';
import type { MeasureOptions, MetricSummary } from './measure';
import { buildReport, isPerfWriteEnabled, writePerfReport } from './report';

/**
 * Reproducible canvas performance baseline. This is measurement only: it never
 * asserts a performance budget and never changes production code. Run with
 * `npm run perf`; add `PERF_WRITE=1` to persist the JSON artifact under
 * `docs/performance/`.
 */
const SIZES: readonly number[] = [100, 1000, 5000, 10000];

const metrics: MetricSummary[] = [];

function record(summary: MetricSummary): void {
  metrics.push(summary);
  console.log(formatMetric(summary));
}

function algorithmicOptions(count: number): MeasureOptions {
  if (count >= 10000) {
    return { warmup: 1, iterations: 3 };
  }
  if (count >= 5000) {
    return { warmup: 1, iterations: 5 };
  }
  if (count >= 1000) {
    return { warmup: 2, iterations: 10 };
  }
  return { warmup: 3, iterations: 20 };
}

function renderOptions(count: number): MeasureOptions {
  if (count >= 10000) {
    return { warmup: 0, iterations: 1 };
  }
  if (count >= 5000) {
    return { warmup: 0, iterations: 2 };
  }
  if (count >= 1000) {
    return { warmup: 1, iterations: 3 };
  }
  return { warmup: 1, iterations: 5 };
}

afterAll(() => {
  const report = buildReport(metrics, [
    'Generated by `npm run perf` under jsdom; timings are machine-dependent and meant for same-host comparison.',
    'Interaction scenarios run against in-memory stores only, decoupled from persistence.',
  ]);

  console.log(`\n${formatMetricsTable(report)}\n`);

  if (isPerfWriteEnabled()) {
    console.log(`Wrote ${writePerfReport(report)}`);
  }
});

describe.each(SIZES)('canvas hot paths (%i elements)', (count) => {
  const elements = generateElements({ count });
  const items = toSelectableItems(elements);
  const options = algorithmicOptions(count);
  const worldBounds = Bounds.fromXYWH(-1_000_000, -1_000_000, 2_000_000, 2_000_000);
  const farAway = Position.create(-1_000_000, -1_000_000);

  it('builds selectable items', () => {
    record(
      measure(
        `toSelectableItems@${count}`,
        'ms',
        () => {
          toSelectableItems(elements);
        },
        options,
      ),
    );

    expect(toSelectableItems(elements)).toHaveLength(count);
  });

  it('hit-tests a point against every item (worst case miss)', () => {
    record(
      measure(
        `findSelectableAt@${count}`,
        'ms',
        () => {
          findSelectableAt(items, farAway);
        },
        options,
      ),
    );

    expect(findSelectableAt(items, farAway)).toBeNull();
  });

  it('selects items inside bounds (worst case: all match)', () => {
    record(
      measure(
        `findSelectablesInBounds@${count}`,
        'ms',
        () => {
          findSelectablesInBounds(items, worldBounds);
        },
        options,
      ),
    );

    expect(findSelectablesInBounds(items, worldBounds)).toHaveLength(count);
  });

  it('summarizes the whole board', () => {
    record(
      measure(
        `describeBoard@${count}`,
        'ms',
        () => {
          describeBoard(elements);
        },
        options,
      ),
    );

    expect(describeBoard(elements)).toContain(`Board with ${count} `);
  });

  it('resolves a connector label against the board', () => {
    const connector = elements.find((element) => element.type === 'connector');

    if (connector === undefined) {
      return;
    }

    record(
      measure(
        `describeElement:connector@${count}`,
        'ms',
        () => {
          describeElement(connector, elements);
        },
        options,
      ),
    );

    expect(describeElement(connector, elements)).toContain('Connector from');
  });

  it('computes the content bounds', () => {
    record(
      measure(
        `elementContentBounds@${count}`,
        'ms',
        () => {
          elementContentBounds(elements);
        },
        options,
      ),
    );

    expect(elementContentBounds(elements)).not.toBeNull();
  });
});

describe.each(SIZES)('canvas interaction re-render (%i elements)', (count) => {
  const elements = generateElements({ count });
  const options = renderOptions(count);

  it('measures mount, pan, zoom, selection and heap delta', () => {
    const store = createCanvasViewportStore(Size.create(1280, 800));
    const selectionStore = createSelectionStore();

    const mountSamples = measureSamples(() => {
      const view = render(
        <Canvas store={store} selectionStore={selectionStore} elements={elements} />,
      );
      view.unmount();
    }, options);
    record(summarize(`render:mount@${count}`, 'ms', mountSamples));
    expect(mountSamples).toHaveLength(options.iterations ?? 1);

    const view = render(
      <Canvas store={store} selectionStore={selectionStore} elements={elements} />,
    );

    const panSamples = measureSamples(() => {
      act(() => {
        store.pan(Position.create(4, 4));
      });
    }, options);
    record(summarize(`render:pan@${count}`, 'ms', panSamples));

    const zoomSamples = measureSamples(() => {
      act(() => {
        store.zoom(1.02, Position.create(400, 300));
      });
    }, options);
    record(summarize(`render:zoom@${count}`, 'ms', zoomSamples));

    const ids = elements.map((element) => element.id.value);
    const evens = ids.filter((_, index) => index % 2 === 0);
    const odds = ids.filter((_, index) => index % 2 === 1);
    let flip = false;
    const selectionSamples = measureSamples(() => {
      const target = flip ? odds : evens;
      flip = !flip;
      act(() => {
        selectionStore.selectMany(target);
      });
    }, options);
    record(summarize(`render:selection@${count}`, 'ms', selectionSamples));

    view.unmount();

    requestGarbageCollection();
    const heapBefore = heapUsedBytes();
    const probe = render(
      <Canvas
        store={createCanvasViewportStore(Size.create(1280, 800))}
        selectionStore={createSelectionStore()}
        elements={elements}
      />,
    );
    const heapAfter = heapUsedBytes();
    probe.unmount();
    record(summarize(`render:heap@${count}`, 'bytes', [heapAfter - heapBefore]));

    expect(store.getSnapshot().scale).toBeGreaterThan(0);
    expect(selectionStore.getSnapshot().selectedIds.length).toBeGreaterThan(0);
  });
});
